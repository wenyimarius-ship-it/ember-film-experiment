export function recommendationSentence(candidate) {
  const match = candidate?.reasons?.[0];
  const film = candidate?.film;
  if (!match || !Number.isInteger(match.dimension) || match.dimension < 0 || match.dimension > 2 ||
      !film || !Object.hasOwn(copyByFilm, film.id) || film.facets?.[match.dimension]?.reason !== match.reason) {
    throw new TypeError('推荐文案需要有效的影片和实际匹配依据。');
  }
  return copyByFilm[film.id][match.dimension];
}

const dimensionNames = ['面对失败', '故事节奏', '故事结局'];
export function matchHeading(match) {
  if (!match || !Number.isInteger(match.dimension) || !dimensionNames[match.dimension] || typeof match.choice !== 'string') {
    throw new TypeError('匹配依据缺少题目维度或偏好。');
  }
  return `${dimensionNames[match.dimension]} → ${match.choice}`;
}

export function matchSummary(candidate) {
  return `匹配 ${candidate.reasons.length} / 3 个故事偏好；仅解释实际匹配的偏好。`;
}
